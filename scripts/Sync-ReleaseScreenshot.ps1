<#
.SYNOPSIS
Brings the README screenshot up to date on a branch before it is tagged.

.DESCRIPTION
Run on the release branch (normally master), right before Push-ReleaseTag.ps1,
so the tagged README already shows the release UI (DEC-060). It runs
update-readme-screenshot.yml for the branch's current commit. When the image
is unchanged it stops there. When it changed, the workflow pushes an
automation branch; this script opens the pull request, waits for its checks,
merges it and fast-forwards the local branch. Requires a clean checkout of the
branch, level with origin, and an authenticated GitHub CLI that can run
workflows and create and merge pull requests.

.EXAMPLE
.\scripts\Sync-ReleaseScreenshot.ps1
#>
[CmdletBinding()]
param(
    [ValidatePattern('^[A-Za-z0-9._/-]+$')]
    [string]$Branch = 'master',

    [ValidateRange(5, 120)]
    [int]$TimeoutMinutes = 40
)

$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'ReleaseConsole.psm1') -Force
Initialize-ReleaseConsole 'README screenshot'

function Invoke-Git([string[]]$Arguments) {
    $output = git @Arguments
    if ($LASTEXITCODE -ne 0) { throw "git $($Arguments -join ' ') failed." }
    return ($output -join "`n").Trim()
}

# The screenshot must come from exactly the commit that will be tagged.
function Assert-CleanBranch {
    if ((Invoke-Git @('branch', '--show-current')) -ne $Branch) { throw "Check out '$Branch' first." }
    if (Invoke-Git @('status', '--porcelain')) { throw 'The working tree is not clean.' }
    Invoke-Git @('fetch', '--quiet', 'origin', $Branch) | Out-Null
    $local = Invoke-Git @('rev-parse', 'HEAD')
    if ($local -ne (Invoke-Git @('rev-parse', "origin/$Branch"))) { throw "'$Branch' differs from origin/$Branch; push or pull first." }
    return $local
}

function Wait-Until([scriptblock]$Done, [string]$What) {
    $deadline = (Get-Date).AddMinutes($TimeoutMinutes)
    while ((Get-Date) -lt $deadline) {
        $result = & $Done
        if ($result) { return $result }
        Start-Sleep -Seconds 10
    }
    throw "Timed out after $TimeoutMinutes minutes waiting for $What."
}

$repository = Invoke-Gh -Arguments @('repo', 'view', '--json', 'nameWithOwner', '--jq', '.nameWithOwner')
$commit = Assert-CleanBranch
Write-Host "Capturing the README screenshot from $Branch at $($commit.Substring(0, 7))." -ForegroundColor Cyan
Write-Host 'Nothing to do here: this window only reports progress and the result.' -ForegroundColor Cyan
Set-Title 'capturing (nothing to do)'

$dispatchedAt = (Get-Date).ToUniversalTime().AddSeconds(-5)
Invoke-Gh -Arguments @('workflow', 'run', 'update-readme-screenshot.yml', '--ref', $Branch, '-f', "branch=$Branch") | Out-Null
$run = Wait-Until -What 'the screenshot run to start' -Done {
    $runs = Invoke-Gh -Arguments @('run', 'list', '--workflow', 'update-readme-screenshot.yml', '--event', 'workflow_dispatch', '--limit', '10', '--json', 'databaseId,headSha,createdAt') | ConvertFrom-Json
    @($runs) | Where-Object { $_.headSha -eq $commit -and ([DateTime]$_.createdAt).ToUniversalTime() -ge $dispatchedAt } | Select-Object -First 1
}
$runUrl = "https://github.com/$repository/actions/runs/$($run.databaseId)"
Write-Activity "Screenshot run: $runUrl"

$script:lastStatus = ''
$finished = Wait-Until -What 'the screenshot run' -Done {
    $state = Get-GhJson "repos/$repository/actions/runs/$($run.databaseId)"
    if ($state.status -ne $script:lastStatus) { Write-Activity "Screenshot run: $($state.status)"; $script:lastStatus = $state.status }
    if ($state.status -eq 'completed') { $state } else { $null }
}
if ($finished.conclusion -ne 'success') {
    Show-Banner -Kind Failure -Title 'the screenshot run failed' -Lines @("Run: $runUrl", 'Do not tag until the README screenshot is current.')
    exit 1
}

# The workflow names its branch automation/readme-screenshot-<source>-<run id>-<attempt>.
$suffix = "-$($finished.id)-$($finished.run_attempt)"
$refs = Get-GhJson "repos/$repository/git/matching-refs/heads/automation/readme-screenshot-"
$automationBranch = @(@($refs) | ForEach-Object { $_.ref -replace '^refs/heads/', '' } | Where-Object { $_.EndsWith($suffix) }) | Select-Object -First 1
if (-not $automationBranch) {
    Show-Banner -Kind Success -Title 'the README screenshot is already current' -Lines @("Tag $Branch at $($commit.Substring(0, 7)) when ready.")
    exit 0
}

Write-Good "The UI changed; opening a pull request from $automationBranch."
$prUrl = Invoke-Gh -Arguments @('pr', 'create', '--base', $Branch, '--head', $automationBranch,
    '--title', "docs: refresh app screenshot before release ($($commit.Substring(0, 7)))",
    '--body', "Generated by update-readme-screenshot.yml run $runUrl from $Branch at $commit, so the release tag includes the current UI (DEC-060).")
Write-Activity "Pull request: $prUrl"
Write-Activity 'Waiting for its checks.'
Set-Title 'waiting for checks (nothing to do)'

$checks = Wait-Until -What 'the pull request checks' -Done {
    # gh pr checks exits 8 while checks are pending and 1 when some failed or none exist yet.
    $json = Invoke-Gh -Arguments @('pr', 'checks', $prUrl, '--json', 'name,bucket') -AllowedExitCodes @(0, 1, 8)
    # Assign before @(...): Windows PowerShell passes a JSON array down the pipeline as one object.
    $parsed = if ([string]::IsNullOrWhiteSpace($json)) { @() } else { $json | ConvertFrom-Json }
    $current = @($parsed)
    if ($current.Count -gt 0 -and -not ($current | Where-Object { $_.bucket -eq 'pending' })) { , $current } else { $null }
}
$failed = @($checks | Where-Object { $_.bucket -in 'fail', 'cancel' })
if ($failed.Count -gt 0) {
    Show-Banner -Kind Failure -Title 'the screenshot pull request failed its checks' -Lines @("Failed: $(($failed | ForEach-Object { $_.name }) -join ', ')", "Pull request: $prUrl")
    exit 1
}

Invoke-Gh -Arguments @('pr', 'merge', $prUrl, '--merge', '--delete-branch') | Out-Null
Invoke-Git @('pull', '--ff-only', '--quiet', 'origin', $Branch) | Out-Null
Show-Banner -Kind Success -Title 'the README screenshot is merged' -Lines @(
    "Pull request: $prUrl",
    "Local $Branch is now at $((Invoke-Git @('rev-parse', '--short', 'HEAD'))); tag this commit.")
